# Runs a local SearXNG for DSH web search. The container binds to loopback only.
#
#   Preview: pwsh -File setup-searxng.ps1 -DryRun
#   Start:   pwsh -File setup-searxng.ps1
#   Stop:    pwsh -File setup-searxng.ps1 -Remove
#
# On an existing installation the active image id is reused and locked. For a
# new installation, pass -Image with an immutable digest or audited versioned
# tag. Omitting -Image otherwise falls back to searxng/searxng:latest.

[CmdletBinding()]
param(
    [switch]$Remove,
    [switch]$DryRun,
    [switch]$SelfTest,
    [switch]$ForceConfig,

    [ValidateRange(1, 65535)]
    [int]$Port = 8888,

    [string]$Image,

    [string]$ConfigDir = (Join-Path $env:USERPROFILE 'searxng')
)

$ErrorActionPreference = 'Stop'

$containerName = 'dsh-searxng'
$settingsPath = Join-Path $ConfigDir 'settings.yml'
$imageLockPath = Join-Path $ConfigDir 'image-id.txt'
$generatedMarker = '# Generated by setup-searxng.ps1 for the local DSH search provider.'
$baseURL = "http://127.0.0.1:$Port"

function Invoke-Docker {
    param([string[]]$Arguments)

    $output = @(& docker @Arguments 2>&1)
    if ($LASTEXITCODE -ne 0) {
        throw "docker $($Arguments -join ' ') failed: $($output -join ' ')"
    }

    return $output
}

function Test-DockerRunning {
    try {
        Invoke-Docker -Arguments @('version', '--format', '{{.Server.Version}}') | Out-Null
        return $true
    } catch {
        return $false
    }
}

function New-CryptoSecret {
    $bytes = [byte[]]::new(24)
    [Security.Cryptography.RandomNumberGenerator]::Fill($bytes)
    return ([Convert]::ToHexString($bytes)).ToLowerInvariant()
}

function New-SettingsContent {
    param([string]$Secret)

    return @"
$generatedMarker
use_default_settings: true
server:
  secret_key: "$Secret"
  limiter: false
  image_proxy: false
search:
  formats:
    - html
    - json
"@
}

function New-SettingsFile {
    $secret = $null
    if (Test-Path -LiteralPath $settingsPath) {
        $existing = Get-Content -LiteralPath $settingsPath -Raw
        if ($existing -notmatch [regex]::Escape($generatedMarker) -and -not $ForceConfig) {
            throw "Refusing to overwrite a settings file not created by this script: $settingsPath. Use -ForceConfig only if that file is disposable."
        }

        $match = [regex]::Match($existing, '(?m)^\s*secret_key:\s*"(?<secret>[0-9a-f]{48})"\s*$')
        if ($match.Success) {
            $secret = $match.Groups['secret'].Value
        }
    }

    if (-not $secret) {
        $secret = New-CryptoSecret
    }

    if (-not (Test-Path -LiteralPath $ConfigDir)) {
        New-Item -ItemType Directory -Path $ConfigDir | Out-Null
    }

    $content = (New-SettingsContent -Secret $secret) + [Environment]::NewLine
    [IO.File]::WriteAllText($settingsPath, $content, [Text.UTF8Encoding]::new($false))
    return $settingsPath
}

function Try-GetContainerImageId {
    $id = @(& docker container inspect $containerName --format '{{.Image}}' 2>$null)
    if ($LASTEXITCODE -eq 0 -and $id.Count -eq 1 -and $id[0] -match '^sha256:[0-9a-f]{64}$') {
        return $id[0]
    }

    return $null
}

function Try-GetLockedImageId {
    if (-not (Test-Path -LiteralPath $imageLockPath)) {
        return $null
    }

    $id = (Get-Content -LiteralPath $imageLockPath -Raw).Trim()
    if ($id -notmatch '^sha256:[0-9a-f]{64}$') {
        return $null
    }

    & docker image inspect $id --format '{{.Id}}' 2>$null | Out-Null
    if ($LASTEXITCODE -eq 0) {
        return $id
    }

    return $null
}

function Resolve-Image {
    if ($Image) {
        return $Image
    }

    $locked = Try-GetLockedImageId
    if ($locked) {
        return $locked
    }

    $active = Try-GetContainerImageId
    if ($active) {
        return $active
    }

    return 'searxng/searxng:latest'
}

if ($SelfTest) {
    $pass = $true
    $check = {
        param([string]$Name, [bool]$Ok)
        if ($Ok) {
            "  PASS  $Name"
        } else {
            "  FAIL  $Name"
            $script:pass = $false
        }
    }

    '--- self test ---'
    $first = New-CryptoSecret
    $second = New-CryptoSecret
    & $check 'secret is 48 hexadecimal characters' ($first -match '^[0-9a-f]{48}$')
    & $check 'secrets are independently generated' ($first -ne $second)

    $yaml = New-SettingsContent -Secret $first
    & $check 'settings enable JSON responses' ($yaml -match '(?m)^[ \t]{4}- json\r?$')
    & $check 'settings disable public image proxying' ($yaml -match '(?m)^[ \t]{2}image_proxy: false\r?$')

    ''
    if ($pass) {
        'self test: all checks passed.'
        exit 0
    }

    'self test: FAILED.'
    exit 1
}

if ($DryRun) {
    "container : $containerName"
    "image     : $(if ($Image) { $Image } else { '(reuse active/locked image, otherwise searxng/searxng:latest)' })"
    "port      : $baseURL (bound to loopback only)"
    "config    : $settingsPath"
    ''
    '--- settings.yml shape that would be written ---'
    New-SettingsContent -Secret '<48 cryptographically random hex characters>'
    ''
    if (-not $Image) {
        'Image note: a new installation without a lock uses latest; pass -Image to pin an audited digest or versioned tag.'
    }
    'dry run: nothing changed.'
    exit 0
}

if (-not (Test-DockerRunning)) {
    throw 'Docker is not running. Start Docker Desktop and retry, or use -DryRun to preview.'
}

if ($Remove) {
    $output = @(& docker rm -f $containerName 2>&1)
    if ($LASTEXITCODE -ne 0) {
        if (($output -join ' ') -match 'No such container') {
            "container ${containerName} is not present."
            exit 0
        }
        throw "Could not remove container ${containerName}: $($output -join ' ')"
    }

    "removed container ${containerName}. The settings file stays at $settingsPath."
    exit 0
}

$resolvedImage = Resolve-Image
"image     : $resolvedImage"
if ($resolvedImage -eq 'searxng/searxng:latest') {
    Write-Warning 'Using mutable searxng/searxng:latest. For reproducibility, pass -Image with an immutable digest or audited versioned tag.'
}

$removeOutput = @(& docker rm -f $containerName 2>&1)
if ($LASTEXITCODE -ne 0 -and ($removeOutput -join ' ') -notmatch 'No such container') {
    throw "Could not replace existing container ${containerName}: $($removeOutput -join ' ')"
}

$written = New-SettingsFile
"wrote $written"

$runOutput = @(
    & docker run -d `
        --name $containerName `
        --restart unless-stopped `
        -p "127.0.0.1:${Port}:8080" `
        -v "${ConfigDir}:/etc/searxng" `
        $resolvedImage 2>&1
)
if ($LASTEXITCODE -ne 0) {
    throw "Could not start SearXNG: $($runOutput -join ' ')"
}

"started container $containerName"
$imageId = @(Invoke-Docker -Arguments @(
    'container', 'inspect', $containerName, '--format', '{{.Image}}'
))[0].Trim()
if ($imageId -notmatch '^sha256:[0-9a-f]{64}$') {
    throw "Started SearXNG, but Docker returned an invalid image id: $imageId"
}
[IO.File]::WriteAllText($imageLockPath, $imageId + [Environment]::NewLine, [Text.UTF8Encoding]::new($false))
"locked image: $imageId"

'waiting for SearXNG to answer...'
$ready = $false
foreach ($attempt in 1..30) {
    Start-Sleep -Seconds 2
    try {
        $probe = Invoke-RestMethod -Uri "$baseURL/search?q=dsh&format=json" -TimeoutSec 10
        if ($null -ne $probe.results) {
            $ready = $true
            break
        }
    } catch {
        # The container can be alive before SearXNG is ready for requests.
    }
}

if (-not $ready) {
    throw "SearXNG did not answer within 60 seconds. Check: docker logs $containerName"
}

"SearXNG is answering JSON at $baseURL"
''
"Now set dsh-web-search-plugin provider=searxng and searxngBaseURL=$baseURL in the profile patch."
